/**
 * Cellar - the shell's one-line notice for a manual module export.
 *
 * Pure wording over the export result, so the notice is tested by running it.
 * The own module's sentence comes first, then what the `#| export <module>` cells
 * did (`exportRole`'s `otherModulesReport`), or that alone when the notebook has
 * no module of its own to report.
 */
import { hazardReport, hazardSummaryClause, humanExportHazards, type ExportHazard } from './exportHazard';
import { otherModulesReport } from './exportRole';
import type { ExportPyResult } from './types';

export function exportShellNotice(r: ExportPyResult): string {
	const fed = otherModulesReport(r, (h) => hazardSummaryClause(humanExportHazards(h as ExportHazard[])));
	const withFed = (own: string) => (fed ? `${own.replace(/\.?$/, '.')} ${fed}` : own);
	if (fed && (r.reason === 'no-target' || r.reason === 'no-cells')) return fed;
	if (r.reason === 'no-target')
		return "Set a target module path (.py, .mojo or .rs) in the notebook's Language and export menu first.";
	if (r.reason === 'no-cells')
		return 'No cells are marked for export - use the export toggle in a cell’s toolbar.';
	// A deliberate refusal, not a failure: Cellar never overwrites a file it did
	// not generate. Said here because no error channel carries this outcome.
	if (r.reason === 'foreign-module')
		return withFed(
			`${r.target} was not generated by Cellar, so it was left untouched - point the export target elsewhere, or delete that file.`
		);
	// A module that was written but cannot be imported may NOT be reported as a
	// plain success. The hazard carries the server's own full sentence, so it
	// REPLACES the success line. EVERY reportable hazard is joined by the shared
	// `hazardReport`, narrowed first by the one human-surface rule, so an
	// agent-only kind neither raises this branch nor rides the sentence.
	const shown = humanExportHazards(r.hazards ?? []);
	return withFed(
		shown.length
			? `Wrote ${r.target}, but ${hazardReport(shown)}`
			: `Exported ${r.count} ${r.count === 1 ? 'cell' : 'cells'} → ${r.target}.`
	);
}
