/** `:dep` arguments as Cargo.toml dependency lines; a bare crate name becomes `name = "*"`. */
function depSpec(arg: string): string {
	const a = arg.trim();
	return /^[A-Za-z0-9_-]+$/.test(a) ? `${a} = "*"` : a;
}

/** Remove Evcxr `:` command lines; return the cleaned source and the `:dep` specs. */
export function stripEvcxrCommands(source: string): { source: string; deps: string[] } {
	const scan = scanRust(source);
	const deps: string[] = [];
	const kept: string[] = [];
	let offset = 0;
	for (const line of source.split('\n')) {
		const inLiteral = scan.stringLineStarts.has(offset) || scan.commentLineStarts.has(offset);
		const trimmed = line.trim();
		if (!inLiteral && /^:[A-Za-z]/.test(trimmed)) {
			const dep = /^:dep\s+(.+)$/.exec(trimmed);
			if (dep) deps.push(depSpec(dep[1]));
		} else kept.push(line);
		offset += line.length + 1;
	}
	return { source: kept.join('\n'), deps };
}

