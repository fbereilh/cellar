/** Placeholder for string and char-literal characters in the mask: not whitespace, not code. */
const STR = '§';

function isIdentChar(c: string | undefined): boolean {
	return c !== undefined && /[A-Za-z0-9_]/.test(c);
}

/**
 * A copy of `src` with comment characters replaced by spaces and string / char
 * literal characters by `STR` (newlines kept, so offsets and lines line up), plus
 * the offsets of every line that STARTS inside a string literal.
 */
interface Scan {
	mask: string;
	/** Offsets (just after a `\n`) where the next line begins inside a string. */
	stringLineStarts: Set<number>;
	/** Offsets (just after a `\n`) where the next line begins inside a block comment. */
	commentLineStarts: Set<number>;
}

function scanRust(src: string): Scan {
	const out: string[] = new Array(src.length);
	const stringLineStarts = new Set<number>();
	const commentLineStarts = new Set<number>();
	const n = src.length;
	let i = 0;
	const fill = (from: number, to: number, ch: string, mode: 'str' | 'comment') => {
		for (let k = from; k < to; k++) {
			if (src[k] === '\n') {
				out[k] = '\n';
				if (k + 1 < to) (mode === 'str' ? stringLineStarts : commentLineStarts).add(k + 1);
			} else out[k] = ch;
		}
	};
	while (i < n) {
		const c = src[i];
		// Line comment.
		if (c === '/' && src[i + 1] === '/') {
			let j = i;
			while (j < n && src[j] !== '\n') j++;
			fill(i, j, ' ', 'comment');
			i = j;
			continue;
		}
		// Block comment, nested.
		if (c === '/' && src[i + 1] === '*') {
			let depth = 1;
			let j = i + 2;
			while (j < n && depth > 0) {
				if (src[j] === '/' && src[j + 1] === '*') {
					depth++;
					j += 2;
				} else if (src[j] === '*' && src[j + 1] === '/') {
					depth--;
					j += 2;
				} else j++;
			}
			fill(i, j, ' ', 'comment');
			i = j;
			continue;
		}
		// Raw string: r"..", r#".."#, br#".."#, cr".."; the r must start a token.
		if (c === 'r') {
			const prev = src[i - 1];
			const startsToken =
				!isIdentChar(prev) || ((prev === 'b' || prev === 'c') && !isIdentChar(src[i - 2]));
			if (startsToken) {
				let j = i + 1;
				let hashes = 0;
				while (src[j] === '#') {
					hashes++;
					j++;
				}
				if (src[j] === '"') {
					const close = '"' + '#'.repeat(hashes);
					const end = src.indexOf(close, j + 1);
					const stop = end < 0 ? n : end + close.length;
					out[i] = 'r';
					for (let k = i + 1; k <= j; k++) out[k] = STR;
					fill(j + 1, stop, STR, 'str');
					i = stop;
					continue;
				}
			}
		}
		// Ordinary (or byte / C) string.
		if (c === '"') {
			let j = i + 1;
			while (j < n && src[j] !== '"') j += src[j] === '\\' ? 2 : 1;
			const stop = Math.min(n, j + 1);
			fill(i, stop, STR, 'str');
			i = stop;
			continue;
		}
		// Char literal versus lifetime / label.
		if (c === "'") {
			let end = -1;
			if (src[i + 1] === '\\') {
				let j = i + 3;
				while (j < n && src[j] !== "'" && src[j] !== '\n') j++;
				if (src[j] === "'") end = j + 1;
			} else {
				const cp = src.codePointAt(i + 1);
				const len = cp !== undefined && cp > 0xffff ? 2 : 1;
				if (cp !== undefined && src[i + 1] !== '\n' && src[i + 1 + len] === "'") end = i + 2 + len;
			}
			if (end > 0) {
				fill(i, end, STR, 'str');
				i = end;
				continue;
			}
		}
		out[i] = c;
		i++;
	}
	return { mask: out.join(''), stringLineStarts, commentLineStarts };
}

const OPEN = '([{';
const CLOSE = ')]}';

/** The offset just past the bracket matching the opener at `i` (all three kinds share a depth). */
function matchClose(mask: string, i: number): number {
	let depth = 0;
	for (let j = i; j < mask.length; j++) {
		const c = mask[j];
		if (OPEN.includes(c)) depth++;
		else if (CLOSE.includes(c)) {
			depth--;
			if (depth === 0) return j + 1;
		}
	}
	return mask.length;
}

function skipWs(mask: string, i: number): number {
	while (i < mask.length && /\s/.test(mask[i])) i++;
	return i;
}

function wordAt(mask: string, i: number): string {
	let j = i;
	while (j < mask.length && isIdentChar(mask[j])) j++;
	return mask.slice(i, j);
}

// ---------------------------------------------------------------------------
// Units: one item, statement, inner attribute or trailing comment
// ---------------------------------------------------------------------------

type UnitKind = 'item' | 'stmt' | 'inner-attr' | 'trivia';

interface Unit {
	kind: UnitKind;
	/** The unit's text, attached comments and attributes included, outer blank lines trimmed. */
	text: string;
	/** A blank line separated it from the unit before it in the cell. */
	blankBefore: boolean;
	/** For an item: a top-level `fn main`. */
	isMainFn?: boolean;
	/** For an item: a `use` declaration (deduplicated across cells). */
	isUse?: boolean;
	/** For a statement: it ends in `;` or a block, so it needs no terminator in `fn main`. */
	terminated?: boolean;
	/** For a statement: it starts with `let`. */
	isLet?: boolean;
	/** For a statement: offsets of its code within `text`, used to wrap a trailing expression. */
	codeStart?: number;
	codeEnd?: number;
	/** Lines of `text` (by index) that begin inside a string literal; never re-indented. */
	stringLines?: Set<number>;
}

/** Keywords that can precede the item keyword (`pub(crate) unsafe extern "C" fn`). */
const BLOCK_LIKE_STMT = new Set(['if', 'match', 'loop', 'while', 'for', 'unsafe', 'async']);

interface Classified {
	kind: 'item' | 'stmt';
	/** How an item ends: at a depth-0 `;` only, or at that or the close of its first depth-0 `{`. */
	end: 'semi' | 'brace' | 'stmt-semi' | 'stmt-block' | 'macro-brace';
	isMainFn?: boolean;
	isUse?: boolean;
	isLet?: boolean;
}

/** Decide what starts at `q` (after any outer attributes). */
function classify(mask: string, q: number): Classified {
	let i = q;
	let w = wordAt(mask, i);
	const stmt = (): Classified => {
		const first = wordAt(mask, q);
		if (first === 'let') return { kind: 'stmt', end: 'stmt-semi', isLet: true };
		if (BLOCK_LIKE_STMT.has(first) || mask[q] === '{') return { kind: 'stmt', end: 'stmt-block' };
		// A labelled loop: 'label: loop { ... }. The label's quote is code in the mask.
		if (mask[q] === "'") {
			const m = /^'[A-Za-z_][A-Za-z0-9_]*\s*:\s*(loop|while|for)\b/.exec(mask.slice(q, q + 80));
			if (m) return { kind: 'stmt', end: 'stmt-block' };
		}
		// A brace-delimited macro call at statement start: name! { ... }
		const mac = /^[A-Za-z_][A-Za-z0-9_:]*\s*!\s*\{/.exec(mask.slice(q, q + 200));
		if (mac) return { kind: 'stmt', end: 'macro-brace' };
		return { kind: 'stmt', end: 'stmt-semi' };
	};
	const next = (from: number) => skipWs(mask, from);
	if (w === 'pub') {
		i = next(i + 3);
		if (mask[i] === '(') i = next(matchClose(mask, i));
		w = wordAt(mask, i);
	}
	// Qualifiers.
	for (;;) {
		if (w === 'unsafe' || w === 'async' || w === 'default' || w === 'safe') {
			const after = next(i + w.length);
			if (mask[after] === '{' || (w === 'async' && wordAt(mask, after) === 'move')) return stmt();
			if (w === 'default' && !/^(fn|type|const|unsafe|async|impl)$/.test(wordAt(mask, after))) return stmt();
			if (w === 'safe' && !/^(fn|static)$/.test(wordAt(mask, after))) return stmt();
			i = after;
			w = wordAt(mask, i);
			continue;
		}
		if (w === 'const') {
			const after = next(i + 5);
			const nw = wordAt(mask, after);
			if (nw === 'fn' || nw === 'unsafe' || nw === 'async' || nw === 'extern') {
				i = after;
				w = nw;
				continue;
			}
			if (mask[after] === '{') return stmt();
			return { kind: 'item', end: 'semi' };
		}
		if (w === 'extern') {
			let after = next(i + 6);
			if (wordAt(mask, after) === 'crate') return { kind: 'item', end: 'semi' };
			while (mask[after] === STR) after++;
			after = next(after);
			if (mask[after] === '{') return { kind: 'item', end: 'brace' };
			i = after;
			w = wordAt(mask, i);
			continue;
		}
		break;
	}
	switch (w) {
		case 'fn': {
			const name = wordAt(mask, next(i + 2));
			return { kind: 'item', end: 'brace', isMainFn: name === 'main' };
		}
		case 'struct':
		case 'enum':
		case 'trait':
		case 'impl':
		case 'mod':
			return { kind: 'item', end: 'brace' };
		case 'union': {
			// Contextual: an item only when a name follows (`union Foo {`).
			const after = next(i + 5);
			return /[A-Za-z_]/.test(mask[after] ?? '') ? { kind: 'item', end: 'brace' } : stmt();
		}
		case 'static':
		case 'type':
			return { kind: 'item', end: 'semi' };
		case 'use':
			return { kind: 'item', end: 'semi', isUse: true };
		case 'macro_rules': {
			const after = next(i + 11);
			return mask[after] === '!' ? { kind: 'item', end: 'brace' } : stmt();
		}
		default:
			return i === q ? stmt() : { kind: 'item', end: 'brace' };
	}
}

/**
 * Characters/words after a block-like statement's `}` that continue the same
 * statement. `pattern` is a struct pattern in the header (`if let P { x } = p {`,
 * `for P { x } in ps {`, `if let A { .. } | B { .. } = v {`): its `}` is not the body's.
 */
function continuesAfterBlock(mask: string, at: number): 'else' | 'pattern' | 'chain' | 'semi' | null {
	const p = skipWs(mask, at);
	if (mask[p] === ';') return 'semi';
	if (mask[p] === '.' || mask[p] === '?') return 'chain';
	const w = wordAt(mask, p);
	if (w === 'else') return 'else';
	if (w === 'in') return 'pattern';
	if ((mask[p] === '=' && mask[p + 1] !== '=') || (mask[p] === '|' && mask[p + 1] !== '|')) return 'pattern';
	return null;
}

/** Where the unit classified at `q` ends (an offset just past its last character). */
function unitEnd(mask: string, q: number, c: Classified): number {
	const n = mask.length;
	let depth = 0;
	let mode = c.end;
	for (let j = q; j < n; j++) {
		const ch = mask[j];
		if (OPEN.includes(ch)) {
			depth++;
			continue;
		}
		if (CLOSE.includes(ch)) {
			depth--;
			if (depth === 0 && ch === '}') {
				if (mode === 'brace' || mode === 'macro-brace') return j + 1;
				if (mode === 'stmt-block') {
					const cont = continuesAfterBlock(mask, j + 1);
					if (cont === 'semi') return skipWs(mask, j + 1) + 1;
					if (cont === 'chain') mode = 'stmt-semi';
					else if (cont !== 'else' && cont !== 'pattern') return j + 1;
				}
			}
			if (depth < 0) depth = 0;
			continue;
		}
		if (ch === ';' && depth === 0) return j + 1;
	}
	return n;
}

/** Extend `end` to the end of its line when the rest of that line is blank in the mask. */
function toLineEnd(mask: string, end: number): number {
	let j = end;
	while (j < mask.length && mask[j] !== '\n' && /\s/.test(mask[j])) j++;
	if (j >= mask.length) return mask.length;
	return mask[j] === '\n' ? j + 1 : end;
}

/** Leading blank lines removed; reports whether any were. */
function trimLeadingBlankLines(text: string): { text: string; removed: number; blank: boolean } {
	const m = /^(?:[ \t]*\r?\n)+/.exec(text);
	if (!m) return { text, removed: 0, blank: false };
	return { text: text.slice(m[0].length), removed: m[0].length, blank: true };
}

