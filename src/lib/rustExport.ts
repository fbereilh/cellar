/** Indent each line by four spaces, except a line that begins inside a string literal. */
function indentUnit(text: string, stringLines: Set<number> | undefined): string {
	return text
		.split('\n')
		.map((line, i) => (stringLines?.has(i) || line.trim() === '' ? line : '    ' + line))
		.join('\n');
}

/**
 * A statement written inside `fn main`. A final expression with no terminator is
 * finished so it compiles: `let` gets its `;`, a block form (`if`, `match`, a loop,
 * a block, a brace macro) gets a `;` so its value is discarded, anything else
 * becomes `let _ = ...;` (Evcxr displays a final value; `fn main` must end in `()`).
 */
function mainStatement(u: Unit, isLast: boolean): string {
	if (!isLast || u.codeStart === undefined || u.codeEnd === undefined) return u.text;
	const before = u.text.slice(0, u.codeStart);
	const code = u.text.slice(u.codeStart, u.codeEnd);
	const after = u.text.slice(u.codeEnd);
	if (u.terminated) return code.endsWith(';') ? u.text : `${before}${code};${after}`;
	return u.isLet ? `${before}${code};${after}` : `${before}let _ = ${code};${after}`;
}

/** Join pieces the way the cell spaced them: a blank line only where it had one. */
function joinPieces(pieces: { text: string; blankBefore: boolean }[]): string {
	let out = '';
	pieces.forEach((p, i) => {
		out += i === 0 ? p.text : (p.blankBefore ? '\n\n' : '\n') + p.text;
	});
	return out;
}

/**
 * A `use` item with comments dropped and whitespace collapsed, attributes and
 * string contents kept, so only truly equal declarations compare equal.
 */
function useKey(text: string): string {
	const mask = scanRust(text).mask;
	let key = '';
	for (let k = 0; k < text.length; k++) key += mask[k] === STR ? text[k] : mask[k];
	return key.replace(/\s+/g, ' ').trim();
}

/**
 * The full `.rs` module for exported cells in document order. Deterministic and
 * idempotent: the same cells always produce the same bytes.
 */
export function generateRustModule(cells: readonly RustExportInput[], sourceName: string): string {
	const plan = planRustExport(cells);
	const header = [RUST_HEADER, `// Source notebook: ${sourceName}`];
	if (plan.deps.length) {
		header.push('// Dependencies (Evcxr :dep lines; add them to Cargo.toml [dependencies]):');
		for (const d of plan.deps) header.push(`//   ${d}`);
	}
	const blocks: string[] = [header.join('\n')];
	const innerAttrs: string[] = [];
	for (const a of plan.analyses)
		for (const u of a.units) if (u.kind === 'inner-attr' && !innerAttrs.includes(u.text)) innerAttrs.push(u.text);
	if (innerAttrs.length) blocks.push(innerAttrs.join('\n'));
	const seenUse = new Set<string>();
	plan.analyses.forEach((a, i) => {
		const isMainCell = plan.mainMode === 'cell' && i === plan.mainIndex;
		const pieces: { text: string; blankBefore: boolean }[] = [];
		const body: Unit[] = [];
		let droppedRun: 'stmt' | 'main' | null = null;
		for (const u of a.units) {
			if (u.kind === 'inner-attr') continue;
			if (u.kind === 'stmt' && isMainCell) {
				body.push(u);
				continue;
			}
			const dropKind: 'stmt' | 'main' | null =
				u.kind === 'stmt' ? 'stmt' : u.kind === 'item' && u.isMainFn && plan.drops[i].main ? 'main' : null;
			if (dropKind) {
				if (droppedRun !== dropKind)
					pieces.push({
						text: dropKind === 'stmt' ? RUST_STATEMENTS_DROPPED_COMMENT : RUST_MAIN_DROPPED_COMMENT,
						blankBefore: u.blankBefore
					});
				droppedRun = dropKind;
				continue;
			}
			droppedRun = null;
			if (u.kind === 'item' && u.isUse) {
				const key = useKey(u.text);
				if (seenUse.has(key)) continue;
				seenUse.add(key);
			}
			pieces.push({ text: u.text, blankBefore: u.blankBefore });
		}
		if (isMainCell && body.length) {
			const stmts = body.map((u, k) => ({
				text: indentUnit(mainStatement(u, k === body.length - 1), u.stringLines),
				blankBefore: k > 0 && u.blankBefore
			}));
			pieces.push({ text: `fn main() {\n${joinPieces(stmts)}\n}`, blankBefore: true });
		}
		const block = joinPieces(pieces).trim();
		if (block) blocks.push(block);
	});
	return blocks.join('\n\n') + '\n';
}

/** The cells' main marks, read the one way: `metadata.cellar.export_main === true`. */
export function isExportMainCell(cell: { metadata?: CellMetadata | null } | null | undefined): boolean {
	return cell?.metadata?.cellar?.export_main === true;
}

/**
 * Is the main-cell toggle offered on this cell? Only in a notebook that can hold
 * export marks and writes a Rust module, and only on a cell that is exported or
 * already carries the mark, so a mark is always clearable where it is.
 */
export function rustMainToggleOffered(
	cell: { cell_type?: string; source?: string; metadata?: CellMetadata | null },
	lang: ExportLanguage | null,
	holdsExport: boolean
): boolean {
	return holdsExport && lang === 'rust' && (isExportCell(cell, 'rust') || isExportMainCell(cell));
}

type RustExportCell = { id: string; cell_type?: string; source?: string; metadata?: CellMetadata | null };

/**
 * What each exported cell of a Rust notebook loses to the module, keyed by cell id.
 * Empty unless the notebook's module language is Rust. Only cells that lost
 * something appear. Derived from the same plan the exporter uses, so the badge and
 * the file cannot disagree.
 */
export function rustExportDrops(
	cells: readonly RustExportCell[],
	lang: ExportLanguage | null
): Map<string, RustCellDrop> {
	const out = new Map<string, RustCellDrop>();
	if (lang !== 'rust') return out;
	const exported = cells.filter((c) => isExportCell(c, 'rust'));
	const plan = planRustExport(exported.map((c) => ({ source: c.source ?? '', main: isExportMainCell(c) })));
	exported.forEach((c, i) => {
		const d = plan.drops[i];
		if (d.statements || d.main) out.set(c.id, d);
	});
	return out;
}

/** Does any EXPORTED cell carry the main mark? (A stale mark on an unexported cell does not count.) */
export function rustMainMarked(cells: readonly RustExportCell[]): boolean {
	return cells.some((c) => isExportCell(c, 'rust') && isExportMainCell(c));
}
