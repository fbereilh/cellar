/** A cell read into units, with its `:dep` lines. */
export interface RustCellAnalysis {
	units: Unit[];
	deps: string[];
}

const analysisCache = new Map<string, RustCellAnalysis>();

/** Split one Evcxr cell into items, statements, inner attributes and trailing comments. */
export function analyzeRustCell(rawSource: string): RustCellAnalysis {
	const cached = analysisCache.get(rawSource);
	if (cached) return cached;
	const { source, deps } = stripEvcxrCommands(rawSource);
	const { mask, stringLineStarts } = scanRust(source);
	const n = source.length;
	const units: Unit[] = [];
	let pos = 0;
	const push = (kind: UnitKind, start: number, end: number, extra: Partial<Unit> = {}) => {
		const raw = source.slice(start, end);
		const lead = trimLeadingBlankLines(raw);
		const text = lead.text.replace(/\s+$/, '');
		if (!text.trim()) return;
		const base = start + lead.removed;
		const stringLines = new Set<number>();
		let line = 0;
		for (let k = 0; k < text.length; k++) {
			if (text[k] === '\n') {
				line++;
				if (stringLineStarts.has(base + k + 1)) stringLines.add(line);
			}
		}
		const unit: Unit = { kind, text, blankBefore: lead.blank && units.length > 0, stringLines, ...extra };
		if (kind === 'stmt' && extra.codeStart !== undefined && extra.codeEnd !== undefined) {
			unit.codeStart = extra.codeStart - base;
			unit.codeEnd = extra.codeEnd - base;
		}
		units.push(unit);
	};
	while (pos < n) {
		const unitStart = pos;
		let p = skipWs(mask, pos);
		if (p >= n) {
			push('trivia', unitStart, n);
			break;
		}
		const inner = /^#!\s*\[/.exec(mask.slice(p, p + 40));
		if (inner) {
			const end = toLineEnd(mask, matchClose(mask, p + inner[0].length - 1));
			push('inner-attr', unitStart, end);
			pos = end;
			continue;
		}
		// Outer attributes belong to whatever follows them.
		for (;;) {
			const outer = /^#\s*\[/.exec(mask.slice(p, p + 40));
			if (!outer) break;
			p = skipWs(mask, matchClose(mask, p + outer[0].length - 1));
		}
		if (p >= n) {
			push('trivia', unitStart, n);
			break;
		}
		const c = classify(mask, p);
		const rawEnd = unitEnd(mask, p, c);
		const end = toLineEnd(mask, rawEnd);
		if (c.kind === 'item') {
			push('item', unitStart, end, { isMainFn: c.isMainFn === true, isUse: c.isUse === true });
		} else {
			// Last code character of the statement, so a terminator lands before a trailing comment.
			let last = rawEnd - 1;
			while (last >= p && /\s/.test(mask[last])) last--;
			const code = mask.slice(p, last + 1);
			const terminated = /[;}]$/.test(code) && (code.endsWith(';') || c.end !== 'stmt-semi');
			push('stmt', unitStart, end, {
				terminated,
				isLet: c.isLet === true,
				codeStart: p,
				codeEnd: last + 1
			});
		}
		pos = end > pos ? end : pos + 1;
	}
	const analysis = { units, deps };
	if (analysisCache.size > 400) analysisCache.clear();
	analysisCache.set(rawSource, analysis);
	return analysis;
}

// ---------------------------------------------------------------------------
// Plan
// ---------------------------------------------------------------------------

/** One exported cell as the plan reads it. */
export interface RustExportInput {
	source: string;
	/** The cell carries the main mark. */
	main: boolean;
}

/** What the export does with each cell. */
export interface RustExportPlan {
	analyses: RustCellAnalysis[];
	/** Index of the main cell (the LAST marked one), or null when none is marked. */
	mainIndex: number | null;
	/** `cell`: the main cell's statements become `fn main`. `fn`: a cell's own `fn main` is kept, if any. */
	mainMode: 'cell' | 'fn';
	/** In `fn` mode, the index of the cell whose `fn main` is kept, or null. */
	keptMainFn: number | null;
	/** Per input index, what was left out. */
	drops: RustCellDrop[];
	/** Every `:dep` spec, deduplicated, in first-seen order. */
	deps: string[];
}

/** Decide, for a list of exported cells in document order, what goes into the module. */
export function planRustExport(cells: readonly RustExportInput[]): RustExportPlan {
	const analyses = cells.map((c) => analyzeRustCell(c.source));
	let mainIndex: number | null = null;
	cells.forEach((c, i) => {
		if (c.main) mainIndex = i;
	});
	const hasStmt = (i: number) => analyses[i].units.some((u) => u.kind === 'stmt');
	const hasMainFn = (i: number) => analyses[i].units.some((u) => u.kind === 'item' && u.isMainFn);
	const mainMode: 'cell' | 'fn' = mainIndex !== null && hasStmt(mainIndex) ? 'cell' : 'fn';
	let keptMainFn: number | null = null;
	if (mainMode === 'fn') analyses.forEach((_, i) => {
		if (hasMainFn(i)) keptMainFn = i;
	});
	const drops = analyses.map((_, i) => ({
		statements: hasStmt(i) && !(mainMode === 'cell' && i === mainIndex),
		main: hasMainFn(i) && !(mainMode === 'fn' && i === keptMainFn)
	}));
	const deps: string[] = [];
	for (const a of analyses) for (const d of a.deps) if (!deps.includes(d)) deps.push(d);
	return { analyses, mainIndex, mainMode, keptMainFn, drops, deps };
}

