/**
 * Cellar — Rust module export: split Evcxr cells into a `.rs` module.
 *
 * A Rust notebook runs on Evcxr, and an Evcxr cell is a list of TOP-LEVEL
 * statements (`let x = 1;`, `println!("{x}");`) mixed with items (`fn`, `struct`,
 * `use`, ...). A `.rs` file holds only items, so concatenating cells the way the
 * Python and Mojo exports do would write a module that does not compile. This
 * module is the one rule that turns exported cells into a valid module:
 *
 *   - every top-level ITEM goes to module level, with the attributes, doc comments
 *     and plain comments written above it;
 *   - the statements of the ONE cell marked as the main cell
 *     (`metadata.cellar.export_main`) go inside a generated `fn main() { ... }`;
 *   - statements in any other exported cell are LEFT OUT, and that is never silent:
 *     a `// CELLAR:` comment marks the spot in the module, the cell carries a badge
 *     (`rustExportDrops`), and the export reports an `ExportHazard`;
 *   - Evcxr commands (`:dep serde = "1"`, `:timing`, ...) are stripped, and the
 *     `:dep` lines are listed in the module's `//` header so they can be copied into
 *     `Cargo.toml`.
 *
 * ## A cell's own `fn main()`
 *
 * The Mojo rule carries over (`$lib/mojoExport`): a module can define `main` once,
 * so the LAST exported cell defining a top-level `fn main()` keeps it and earlier
 * ones are left out. The marked main cell's statements outrank it - a main cell
 * with statements generates `fn main()` from them, and every user `fn main()` is
 * then left out, since keeping one would define `main` twice. A main cell with NO
 * statements generates nothing, so the Mojo rule decides.
 *
 * ## How a cell is read
 *
 * A small hand-written lexer, not a Rust parser: it knows strings (escaped, raw
 * `r#"..."#`, byte and C strings), char literals versus lifetimes, `//` and nested
 * `/* *\/` comments, and `()[]{}` depth. Everything structural is decided on a
 * MASKED copy of the source where string and comment contents are blanked out, so
 * a keyword or a `;` inside a string is never read as code. That is enough to tell
 * an item from a statement because Rust marks every item with a leading keyword.
 *
 * Known limits, each a deliberate stop rather than a guess:
 *   - A statement-position macro with braces (`thread_local! { ... }`) is read as a
 *     statement, so outside the main cell it is left out (and reported).
 *   - A `?` at the top level of the main cell does not compile inside the generated
 *     `fn main()`, which returns `()`.
 *   - A statement left out of a non-main cell is gone from the module even when the
 *     main cell reads a variable it defined; the badge and the hazard say so.
 *   - A const-generic block in an item header (`impl Foo<{ N }>`) ends the header
 *     early, since `<>` are not tracked.
 *   - An item defined twice across exported cells (a function redefined in a later
 *     cell, which Evcxr allows) is written twice and will not compile. Identical
 *     `use` lines are the one duplicate removed, because they are routine.
 *
 * Browser-safe and pure: the server's exporter (`server/export-py.ts`) and the
 * cell badge (`Cell.svelte`, through `LiveNotebook`) read the same plan, so the
 * badge can never disagree with the file.
 */

