/** What one exported cell lost to the export. */
export interface RustCellDrop {
	/** Its top-level statements were left out. */
	statements: boolean;
	/** Its own top-level `fn main()` was left out. */
	main: boolean;
}

/** The badge text for a cell's drops, or null when it lost nothing. */
export function rustDropBadge(drop: RustCellDrop | null | undefined): string | null {
	if (!drop) return null;
	if (drop.statements && drop.main) return RUST_CODE_DROPPED_BADGE;
	if (drop.statements) return RUST_STATEMENTS_DROPPED_BADGE;
	if (drop.main) return RUST_MAIN_DROPPED_BADGE;
	return null;
}

/**
 * The badge's tooltip: what was left out and why. `mainMarked` says whether the
 * notebook has a main cell, because the remedy differs: with none, marking one is
 * how statements get into the module at all.
 */
export function rustDropReason(drop: RustCellDrop, mainMarked: boolean): string {
	const parts: string[] = [];
	if (drop.statements) {
		parts.push(
			mainMarked
				? 'The top-level statements in this cell are not in the .rs module: only the main cell\'s statements go into fn main(). Its items (fn, struct, use, ...) are exported. Move the statements into the main cell to keep them.'
				: 'The top-level statements in this cell are not in the .rs module, because no cell is marked as the main cell. Its items (fn, struct, use, ...) are exported. Mark a cell as the main cell to put its statements in fn main().'
		);
	}
	if (drop.main) {
		parts.push(
			'This cell\'s fn main() is not in the .rs module: a module defines main only once, and either the main cell\'s statements or a later cell\'s fn main() took that place.'
		);
	}
	return parts.join(' ');
}

